  function translate(map){
    const entries=Object.entries({...common,...map}).sort((a,b)=>b[0].length-a[0].length);
    const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);
    const nodes=[]; while(walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(node=>{let value=node.nodeValue; entries.forEach(([from,to])=>{value=value.split(from).join(to)}); node.nodeValue=value});
    document.querySelectorAll('input[placeholder],textarea[placeholder],input[value]').forEach(el=>{
      const attr=el.hasAttribute('placeholder')?'placeholder':'value'; let value=el.getAttribute(attr)||'';
      entries.forEach(([from,to])=>{value=value.split(from).join(to)}); el.setAttribute(attr,value);
    });
  }

